import type { CategoryData } from './documents';

type SimpleCategory = {
  id: string;
  name: string;
  documents: string[];
};

const toCategoryData = (categories: SimpleCategory[]): CategoryData[] =>
  categories.map((category) => ({
    id: category.id,
    name: category.name,
    iconName: 'FileText',
    color: 'text-emerald-700',
    bgColor: 'bg-emerald-50',
    borderColor: 'border-emerald-200',
    documents: category.documents.map((name, index) => ({
      id: `${category.id}-${index + 1}`,
      name,
      description: '',
      howToGet: '',
      canDelegate: false,
    })),
  }));

