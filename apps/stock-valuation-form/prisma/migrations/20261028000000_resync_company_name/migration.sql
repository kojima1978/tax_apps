-- 会社名の列を入力データの欄（第1表の1・f12）へ揃え直す。
--
-- この列は様式の会社名欄の写しで、画面の自動保存が毎回その欄の値で上書きする。
-- 案件の複製だけが列に「（コピー）」を足していたため、複製を開くまでの間、列と欄が
-- 食い違っていた（会社一覧の見出しはこの列から作るので、会社そのものが
-- 「○○（コピー）」という名前に見えていた）。足すのをやめたので、既にできている
-- 食い違いもここで直す。
--
-- 欄を持たない行（data が空、取込前の案件）は触らない ── 空で上書きすると、
-- 一覧から会社名が消える。
UPDATE "ValuationCase"
   SET "companyName" = btrim("data" -> 'table1_1' ->> 'f12')
 WHERE jsonb_typeof("data" -> 'table1_1' -> 'f12') = 'string'
   AND btrim("data" -> 'table1_1' ->> 'f12') <> "companyName";
