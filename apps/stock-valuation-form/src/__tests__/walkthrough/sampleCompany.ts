/** 第5表の明細1行（科目・相続税評価額・帳簿価額・備考）。単位はいずれも千円。 */
type DetailRow = readonly [name: string, evaluated: string, book: string, note: string];

/** 明細の配列を様式のフィールド名（a_1_1 …／l_1_1 …）へ展開する。 */
function detailFields(prefix: 'a' | 'l', rows: readonly DetailRow[]): Fields {
  const fields: Fields = {};
  rows.forEach((row, index) => {
    row.forEach((value, column) => {
      if (value !== '') fields[`${prefix}_${index + 1}_${column + 1}`] = value;
    });
  });
  return fields;
}

