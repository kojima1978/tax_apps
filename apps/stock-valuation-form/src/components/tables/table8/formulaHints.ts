import { hv, rv } from '@/lib/formulaHint';
import type { calcTable8 } from './Table8Grid';

// 第7表の3（第8表）の自動計算欄に出すツールチップ。
// ⑭〜⑰は「4つのうち1つだけが埋まる」欄で、どれが埋まるかは第2表の判定と第1表の2の会社規模で決まる。
// 空欄になった欄にも「なぜ空欄なのか」を出さないと、計算が止まっているのと区別が付かない。

type Calc = ReturnType<typeof calcTable8>;

/** ⑤・⑲の「第5表の㋺＋（㊁－㋭）」。20％判定で加算しなかったときはその理由を書く */
const stockBookHint = (c: Calc): string => {
  const base = `第５表の㋺（株式等の帳簿価額の合計額）${rv(c.t5Stock, 1)}千円`;
  // ㊁が未入力のうちは20％判定の話をしても意味がないので、転記元だけ出す
  if (c.inKind.eval === 0) return base;
  if (c.inKind.diff === 0) {
    return `${base}\n現物出資等受入れ資産（㊁）は総資産の20％以下のため、（㊁－㋭）は加算しません（評価通達186－2）`;
  }
  return `${base} ＋（㊁ ${hv(c.inKind.eval, 1)} － ㋭ ${hv(c.inKind.book, 1)}）＝ ${rv(c.v5, 1)}千円`
    + `\n現物出資等受入れ資産が総資産の${c.inKind.ratio.toFixed(1)}％（20％超）のため差額を加算しています（評価通達186－2）`
    + '\n㊁㋭に株式等以外の資産に係る金額が含まれるときは、その分を除いた金額に読み替えてください';
};

const NO_TAX_DEDUCTION = '所得税・法人税の時価評価（中心的な同族株主に該当する場合）では、'
  + '評価差額に対する法人税額等相当額を控除しないため0とします';

export function table8Hints(c: Calc, specialMarketValueRules: boolean): Record<string, string> {
  const cls = c.cls;
  // ⑭〜⑰のどれを使うか。比準要素数1の会社の判定が会社規模より優先する
  const picked = cls.hijun1 ? '⑭（比準要素数１の会社）'
    : cls.big ? '⑮（大会社）'
      : cls.mid ? '⑯（中会社）'
        : cls.small ? '⑰（小会社）'
          : null;
  const notPicked = picked === null
    ? '第２表の判定と第１表の２の会社規模が決まると、⑭〜⑰のどれを記載するかが決まります'
    : `この評価会社は ${picked} を記載するため、この欄は記載しません`;
  const lText = cls.lRate === null ? 'Ｌ' : cls.lRate.toFixed(2);

  return {
    '①': `第５表の⑤（相続税評価額による純資産価額）${rv(c.v1, 1)}千円`,
    '②': `第５表のイ（課税時期現在の株式等の価額の合計額）${rv(c.v2, 1)}千円`,
    '③': `① ${hv(c.v1, 1)} － ② ${hv(c.v2, 1)} ＝ ${rv(c.v3, 1)}千円`,
    '④': `第５表の⑥（帳簿価額による純資産価額）${rv(c.v4, 1)}千円`,
    '⑤': stockBookHint(c),
    '⑥': `④ ${hv(c.v4, 1)} － ⑤ ${hv(c.v5, 1)} ＝ ${rv(c.v6, 1)}千円`,
    '⑦': `③ ${hv(c.v3, 1)} － ⑥ ${hv(c.v6, 1)} ＝ ${rv(c.v7, 1)}千円（マイナスのときは0）`,
    '⑧': specialMarketValueRules ? NO_TAX_DEDUCTION
      : `⑦ ${hv(c.v7, 1)}千円 × 38％ ＝ ${rv(c.v8, 1)}千円（端数切捨て）`,
    '⑨': `③ ${hv(c.v3, 1)} － ⑧ ${hv(c.v8, 1)} ＝ ${rv(c.v9, 1)}千円`,
    '⑩': `第５表の⑩（課税時期現在の発行済株式数）${rv(c.v10)}株`,
    '⑪': `⑨ ${hv(c.v9, 1)}千円 × 1,000 ÷ ⑩ ${hv(c.v10)}株 ＝ ${rv(c.v11)}円（円未満切捨て）`,

    '⑫': `第７表の２の比準価額 ${rv(c.v12)}円（㉚ → ㉖ → ㉔ の順に、記載のあるものを使います）`,
    '⑬': `⑪ ${rv(c.v11)}円 と同じ金額です`,
    '⑭': cls.hijun1
      ? `⑬ ${rv(c.v13)}円 と（⑫ ${hv(c.v12)}円 × 0.25 ＋ ⑬ ${hv(c.v13)}円 × 0.75）のうち低い方`
        + `\n＝ ${rv(c.v14)}円（円未満切捨て）`
      : notPicked,
    '⑮': cls.big
      ? `⑫ ${hv(c.v12)}円 と ⑬ ${hv(c.v13)}円 のうち低い方 ＝ ${rv(c.v15)}円`
      : notPicked,
    '⑯': cls.mid
      ? `（⑫ ${hv(c.v12)}円 と ⑬ ${hv(c.v13)}円 の低い方）× Ｌ ${lText} ＋ ⑬ ${hv(c.v13)}円 ×（1 － ${lText}）`
        + `\n＝ ${rv(c.v16)}円（円未満切捨て。Ｌの割合は第１表の２の会社規模で決まります）`
      : notPicked,
    '⑰': cls.small
      ? `⑬ ${rv(c.v13)}円 と（⑫ ${hv(c.v12)}円 × 0.5 ＋ ⑬ ${hv(c.v13)}円 × 0.5）のうち低い方`
        + `\n＝ ${rv(c.v17)}円（円未満切捨て）`
      : notPicked,

    '⑱': `第５表のイ（株式等の相続税評価額の合計額）${rv(c.v18, 1)}千円`
      + '\n第５表と異なる金額を使うときは、この欄に直接入力すると上書きできます',
    '⑲': stockBookHint(c)
      + '\n第５表と異なる金額を使うときは、この欄に直接入力すると上書きできます',
    '⑳': `⑱ ${hv(c.v18, 1)} － ⑲ ${hv(c.v19, 1)} ＝ ${rv(c.v20, 1)}千円（マイナスのときは0）`,
    '㉑': specialMarketValueRules ? NO_TAX_DEDUCTION
      : `⑳ ${hv(c.v20, 1)}千円 × 38％ ＝ ${rv(c.v21, 1)}千円（端数切捨て）`,
    '㉒': `⑱ ${hv(c.v18, 1)} － ㉑ ${hv(c.v21, 1)} ＝ ${rv(c.v22, 1)}千円`,
    '㉓': `第５表の⑩（課税時期現在の発行済株式数）${rv(c.v23)}株`,
    '㉔': `㉒ ${hv(c.v22, 1)}千円 × 1,000 ÷ ㉓ ${hv(c.v23)}株 ＝ ${rv(c.v24)}円（円未満切捨て）`,

    '㉕': `第５表の⑫（記載がないときは⑪）の1株当たりの純資産価額 ${rv(c.v25)}円`,
    '㉖': `S1の金額 ${rv(c.s1)}円（${picked ?? '⑭〜⑰が未確定'}）＋ S2の金額 ㉔ ${hv(c.v24)}円`
      + `\n＝ ${rv(c.v26)}円`,
    '㉗': `㉕ ${hv(c.v25)}円 と ㉖ ${hv(c.v26)}円 のうち低い方 ＝ ${rv(c.v27)}円`,
  };
}
